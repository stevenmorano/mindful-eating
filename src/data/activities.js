export const getActivities = () => defaultActivities;

export const getActivityCategories = () => {
  const counts = getActivities().reduce((acc, activity) => {
    const category = activity.category;
    acc[category] = (acc[category] || 0) + 1;
    return acc;
  }, {});

  return Object.entries(counts).map(([category, count]) => ({
    category,
    count,
    ...(categoryMeta[category] || {
      label: category,
      description: "Saved pause ideas",
      icon: "custom",
    }),
  }));
};

export const addCustomActivity = (text, category = "Custom") => {
  let custom = [];
  try {
    const parsed = JSON.parse(localStorage.getItem('mm-custom-activities') || '[]');
    custom = Array.isArray(parsed) ? parsed : [];
  } catch {
    custom = [];
  }
  custom.push({ text, category });
  localStorage.setItem('mm-custom-activities', JSON.stringify(custom));
};

export const getRandomSnack = () => {
  const randomIndex = Math.floor(Math.random() * snacks.length);
  return snacks[randomIndex];
};
